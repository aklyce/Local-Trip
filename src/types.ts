export interface Place {
  name: string
  lat: number
  lon: number
  /** ISO 3166-1 alpha-2, e.g. "US". Needed for holiday lookups. */
  countryCode?: string
  /** Optional state/region label, e.g. "California". */
  region?: string
}

export interface DailyWeather {
  date: string
  tempMax: number
  tempMin: number
  /** Forecast gives a probability (%); historical data gives a sum (mm). */
  precipitation: number | null
  weatherCode: number
}

export interface WeatherResult {
  /** "forecast" for the next ~16 days, otherwise same dates from the previous year. */
  kind: 'forecast' | 'historical'
  days: DailyWeather[]
}

export interface EventItem {
  id: string
  name: string
  date: string
  /** HH:MM local time */
  time?: string
  url: string
  venue?: string
  image?: string
  /** e.g. "Music", "Sports" */
  category?: string
}

export interface Holiday {
  date: string
  localName: string
  name: string
  /** true = only observed in some states/regions (Nager.Date `global: false`). */
  regional?: boolean
}

/** Driving route from OSRM, or an explicit "no road route" result (FR-12). */
export type RouteResult =
  | {
      kind: 'route'
      distanceKm: number
      durationMin: number
      /** Simplified road geometry as [lat, lon] pairs, for the map. */
      geometry: [number, number][]
    }
  | { kind: 'none' }

/**
 * Cached state of one external service (FR-10, FR-11). Services load and fail independently,
 * so one broken API never blanks the dashboard.
 * `data` is the last *successful* result and survives a later failed refresh (then it is stale).
 */
export interface ServiceState<T> {
  /** Outcome of the most recent attempt. */
  status: 'ok' | 'error' | 'timeout' | 'unconfigured'
  data?: T
  /** When `data` was fetched (ms since epoch). */
  fetchedAt?: number
  error?: string
}

export type ServiceKey = 'weather' | 'events' | 'holidays' | 'route'

export interface TripSnapshot {
  weather?: ServiceState<WeatherResult>
  events?: ServiceState<EventItem[]>
  holidays?: ServiceState<Holiday[]>
  route?: ServiceState<RouteResult>
}

/** One packing/preparation item (FR-15 to FR-18). */
export interface ChecklistItem {
  /** Stable id so edits survive reloads and reordering. */
  id: string
  label: string
  done: boolean
  /** true = generated by the suggestion rules ("Suggested"), false = added by the user. */
  auto: boolean
}

export interface Trip {
  id?: number
  origin: Place
  destination: Place
  /** YYYY-MM-DD */
  startDate: string
  endDate: string
  createdAt: number
  snapshot?: TripSnapshot
  /** Packing list. Missing only on trips saved before schema v2. */
  checklist?: ChecklistItem[]
  /** Lower-cased labels of suggestions the user removed, so refresh never re-adds them. */
  dismissedSuggestions?: string[]
  notes?: string
}
